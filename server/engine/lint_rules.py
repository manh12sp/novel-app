ALL: list[dict] = []

for prefix, cat, sev, fixable, name, advice, words in WORD_GROUPS:
    for w in words:
        ALL.append({"id": f"{prefix}:{w}", "kind": "word", "pattern": w, "category": cat,
                    "name": f"{name}·{w}", "term": w, "severity": sev,
                    "fixable": bool(fixable), "advice": f"「{w}」{advice}"})

for rid, cat, name, pat, sev, fixable, advice in REGEX_RULES:
    ALL.append({"id": rid, "kind": "regex", "pattern": pat, "category": cat, "name": name,
                "severity": sev, "fixable": bool(fixable), "advice": advice})

for rid, cat, name, sev, fixable, advice in DOC_RULES:
    ALL.append({"id": rid, "kind": "doc", "pattern": "", "category": cat, "name": name,
                "severity": sev, "fixable": bool(fixable), "advice": advice})

RULE_COUNT = len(ALL)
CATEGORIES = sorted({r["category"] for r in ALL})
CATEGORY_COUNTS = {c: sum(1 for r in ALL if r["category"] == c) for c in CATEGORIES}


def summary() -> str:
    return (f"Có sẵn {RULE_COUNT} quy tắc, gồm {len(CATEGORIES)} loại: "
            + "、".join(f"{c} {CATEGORY_COUNTS[c]}" for c in CATEGORIES) + "。")


if __name__ == "__main__":        # `python -m server.engine.lint_rules` 能直接看条数
    print(summary())
    print("Tự sửa được: ", sum(1 for r in ALL if r["fixable"]))
